export function getSticker(id: string): StickerDef | undefined {
  return STICKERS.find((sticker) => sticker.id === id);
}

export function stickersInPack(packId: string): StickerDef[] {
  return STICKERS.filter((sticker) => sticker.packId === packId);
}
