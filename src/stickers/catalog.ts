type Row = [string, ArtKey, Rarity, Unlock, Palette];

function rows(packId: string, items: Row[]): StickerDef[] {
  return items.map(([name, art, rarity, unlock, colors]) => ({
    id: `${packId}-${slug(name)}`,
    packId,
    name,
    art,
    rarity,
    unlock,
    price: unlock === 'coins' ? coinPrice(rarity) : 0,
    colors,
  }));
}

